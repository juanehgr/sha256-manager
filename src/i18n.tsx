export type Lang = keyof typeof dict;
export type I18nKey = keyof typeof dict.es;

type I18nApi = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: I18nKey, vars?: Record<string, string | number>) => string;
};

const Ctx = createContext<I18nApi | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const s = localStorage.getItem("lang");
    return s === "en" || s === "es" ? s : "es";
  });
  const setLang = (l: Lang) => {
    localStorage.setItem("lang", l);
    setLangState(l);
    document.documentElement.lang = l;
  };
  const t = useMemo(() => {
    return (key: I18nKey, vars?: Record<string, string | number>) => {
      let s = String(dict[lang][key] || dict.es[key] || key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      }
      return s;
    };
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error("i18n");
  return v;
}
